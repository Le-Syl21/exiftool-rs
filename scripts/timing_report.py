#!/usr/bin/env python3
"""The timing page of the published report: every CLI case of the judges,
run by Perl's exiftool and by exiftool-rs, with each side's time.

usage: timing_report.py TIMES.tsv [--rs VERSION] [--exiftool VERSION] > timings.html

TIMES.tsv is what scripts/compare_cli.py appends with CLI_TIMES=TIMES.tsv:
case file, number, kind, arguments, Perl's seconds, the port's seconds,
identical (1 or 0). Each time is a whole process, from start to exit, so it
includes the start of each program (perl compiling ExifTool's modules, the
port loading its embedded ones).
"""
import argparse
import html
import os
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from parity_report import CSS  # noqa: E402  (the same look as the parity page)

# what each case file of the judges exercises
TITLES = {
    "cli_cases.txt": "The command line",
    "cli_cases_options.txt": "Every option",
    "cli_cases_program.txt": "The main program",
    "cli_cases_subs_a.txt": "The script's subs (1)",
    "cli_cases_subs_b.txt": "The script's subs (2)",
    "cli_cases_get_image_info.txt": "Reading (GetImageInfo)",
    "cli_cases_set_image_info.txt": "Writing (SetImageInfo)",
    "cli_cases_full_modules.txt": "With all the optional modules",
}

EXTRA_CSS = """
.bars{display:flex;flex-direction:column;gap:2px;min-width:8rem}
.bar{height:.42rem;border-radius:2px;background:var(--muted);opacity:.55}
.bar.rs{background:var(--accent);opacity:1}
td.n,th.n{text-align:right}
td.g{color:var(--accent);font-weight:600}
td.l{color:var(--warn);font-weight:600}
td.args{white-space:normal;word-break:break-all;max-width:36rem}
.summary td,.summary th{white-space:normal}
.note{color:var(--muted);font-size:.85rem;max-width:46rem;margin:.2rem 0 1rem}
nav.top{max-width:70rem;margin:0 auto;padding:1rem 1.5rem 0;font-size:.85rem}
"""


def esc(s):
    return html.escape(str(s), quote=True)


def read(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 7:
                continue
            case_file, n, kind, args, perl, port, same = parts
            rows.append((case_file, int(n), kind, args, float(perl), float(port), same == "1"))
    return rows


def gain(perl, port):
    return (perl - port) / perl * 100 if perl else 0.0


def ms(s):
    return f"{s * 1000:,.0f}"


def render(rows, rs_ver, et_ver):
    tp = sum(r[4] for r in rows)
    tr = sum(r[5] for r in rows)
    faster = sum(1 for r in rows if r[5] < r[4])
    ratios = [r[4] / r[5] for r in rows if r[5] > 0]
    median = statistics.median(ratios) if ratios else 0
    same = sum(1 for r in rows if r[6])
    by_file = {}
    for r in rows:
        by_file.setdefault(r[0], []).append(r)
    out = []
    w = out.append
    w(f"""<!doctype html><html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>exiftool-rs timings</title>
<meta name="description" content="Every command line of exiftool-rs's judges, run by Perl ExifTool {esc(et_ver)} and by exiftool-rs {esc(rs_ver)}: the time each takes, case by case.">
<link rel="canonical" href="https://le-syl21.github.io/exiftool-rs/timings.html">
<style>{CSS}{EXTRA_CSS}</style></head><body>
<nav class="top"><a href="./">Parity report</a> · Timings</nav>
<header class="hero">
  <p class="eyebrow">Perl vs Rust, command by command</p>
  <h1>How long each command takes</h1>
  <p class="sub">Every command line the judges compare (each option of the
     <code>exiftool</code> application, reads, writes, the script's subs), run
     once by Perl <strong>ExifTool {esc(et_ver)}</strong> and once by
     <strong>exiftool-rs {esc(rs_ver)}</strong> on the same machine. Each time is
     the whole process, start included. Regenerated by CI on every release.</p>
  <div class="tiles">
    <div class="tile"><span class="n">{tp:,.1f} s</span><span class="l">Perl ExifTool, all {len(rows)} commands</span></div>
    <div class="tile"><span class="n">{tr:,.1f} s</span><span class="l">exiftool-rs, the same commands</span></div>
    <div class="tile {'good' if tr < tp else 'warn'}"><span class="n">{gain(tp, tr):+.0f} %</span><span class="l">time saved overall</span></div>
    <div class="tile"><span class="n">×{median:.1f}</span><span class="l">median speed-up per command</span></div>
  </div>
  <p class="meta">{faster} of {len(rows)} commands faster · {same} of {len(rows)} with
     an output identical to Perl's (the <a href="./">parity report</a> covers
     the rest of the comparison) · one run each, on a GitHub Actions runner</p>
</header>
<main>""")
    w('<h2>By case file</h2><div class="panel scroll"><table class="summary"><thead><tr>'
      '<th>Case file</th><th class="n">Commands</th><th class="n">Perl (s)</th>'
      '<th class="n">exiftool-rs (s)</th><th class="n">Saved</th></tr></thead><tbody>')
    for f, rs in by_file.items():
        p, q = sum(r[4] for r in rs), sum(r[5] for r in rs)
        g = gain(p, q)
        w(f'<tr><td><a href="#{esc(f)}">{esc(TITLES.get(f, f))}</a></td><td class="n">{len(rs)}</td>'
          f'<td class="n">{p:,.1f}</td><td class="n">{q:,.1f}</td>'
          f'<td class="n {"g" if g >= 0 else "l"}">{g:+.0f} %</td></tr>')
    w("</tbody></table></div>")
    w('<h2 class="readh">Command by command</h2>'
      '<p class="note">The bars compare the two times of a command (grey: Perl, green:'
      ' exiftool-rs). A case marked ✗ printed or wrote something different from'
      ' Perl on that run.</p>')
    for f, rs in by_file.items():
        p, q = sum(r[4] for r in rs), sum(r[5] for r in rs)
        w(f'<details id="{esc(f)}"><summary><span class="fname">{esc(TITLES.get(f, f))}</span>'
          f'<span class="cnt">{len(rs)} commands · {gain(p, q):+.0f} %</span></summary>')
        w('<div class="scroll"><table><thead><tr><th class="n">#</th><th>Arguments</th>'
          '<th class="n">Perl (ms)</th><th class="n">exiftool-rs (ms)</th><th class="n">Saved</th>'
          '<th></th><th class="c">ISO</th></tr></thead><tbody>')
        for _, n, kind, args, perl, port, ok in rs:
            top = max(perl, port) or 1
            g = gain(perl, port)
            cls = "" if ok else ' class="d"'
            w(f'<tr{cls}><td class="n">{n}</td><td class="args">{esc(args)}</td>'
              f'<td class="n">{ms(perl)}</td><td class="n">{ms(port)}</td>'
              f'<td class="n {"g" if g >= 0 else "l"}">{g:+.0f} %</td>'
              f'<td><div class="bars"><div class="bar" style="width:{perl / top * 100:.0f}%"></div>'
              f'<div class="bar rs" style="width:{port / top * 100:.0f}%"></div></div></td>'
              f'<td class="c">{"✓" if ok else "✗"}</td></tr>')
        w("</tbody></table></div></details>")
    w("<script>function o(){var e=location.hash&&document.getElementById(location.hash.slice(1));"
      "if(e&&e.tagName==='DETAILS')e.open=true}addEventListener('hashchange',o);o()</script>")
    w("</main><footer>Generated from <code>compare_cli.py</code> (CLI_TIMES) · "
      "<a href=\"https://github.com/Le-Syl21/exiftool-rs\">Le-Syl21/exiftool-rs</a></footer>"
      "</body></html>")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv")
    ap.add_argument("--rs", default="")
    ap.add_argument("--exiftool", default="")
    a = ap.parse_args()
    rows = read(a.tsv)
    if not rows:
        sys.exit("no timing rows in " + a.tsv)
    sys.stdout.write(render(rows, a.rs, a.exiftool))


if __name__ == "__main__":
    main()
