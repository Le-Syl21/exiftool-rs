#!/usr/bin/perl
# Canon's second-generation custom functions, `%CanonCustom::Functions2`, as data.
#
# A custom function is a tag id with one or more variants; ExifTool takes the
# first variant whose Condition holds -- a regular expression on the model
# name or the number of values stored -- and converts the values with that
# variant's ValueConv and PrintConv. Translating those choices by hand is how a
# port ends up decoding a body it does not know as a 1D Mark III, so they are
# carried over as written. A Condition, a conversion or a hash key this script
# does not understand stops it rather than being approximated.
#
# Usage: perl scripts/gen_canon_custom2.pl /path/to/exiftool/lib > src/tags/canon_custom2_generated.rs

use strict;
use warnings;

my $lib = $ARGV[0] || '../exiftool/lib';
die "Cannot find $lib\n" unless -d $lib;
unshift @INC, $lib;
require Image::ExifTool;
require Image::ExifTool::CanonCustom;

no warnings 'once';
my $table = \%Image::ExifTool::CanonCustom::Functions2;
my $version = $Image::ExifTool::VERSION;

my (@regexes, %regex_id);
sub regex_id {
    my ($pat) = @_;
    unless (exists $regex_id{$pat}) {
        $regex_id{$pat} = scalar @regexes;
        push @regexes, $pat;
    }
    return $regex_id{$pat};
}

sub rust_str {
    my ($s) = @_;
    $s =~ s/\\/\\\\/g;
    $s =~ s/"/\\"/g;
    $s =~ s/\n/\\n/g;
    return "\"$s\"";
}

# One Condition as a Rust `Cond`.
sub cond_to_rust {
    my ($cond, $where) = @_;
    return 'Cond::Always' unless defined $cond;
    (my $c = $cond) =~ s/^\s+|\s+$//g;
    return "Cond::Count($1)" if $c =~ /^\$count\s*==\s*(\d+)$/;
    my @alts;
    for my $alt (split /\s+or\s+/, $c) {
        $alt =~ /^\$\$self\{Model\}\s*(=~|!~)\s*\/([^\/]*)\/$/
            or die "$where: unsupported condition: $cond\n";
        push @alts, sprintf('(&RE_%d, %s)', regex_id($2), $1 eq '!~' ? 'true' : 'false');
    }
    return 'Cond::Model(&[' . join(', ', @alts) . '])';
}

# A PrintConv hash, or one element of a PrintConv list, as a Rust `Print`.
sub print_to_rust {
    my ($conv, $where) = @_;
    return 'Print::Raw' unless defined $conv;
    unless (ref $conv) {
        return 'Print::Expr(' . rust_str($conv) . ')';
    }
    ref $conv eq 'HASH' or die "$where: unsupported PrintConv: " . ref($conv) . "\n";
    my (@map, $bits);
    for my $k (sort { ($a =~ /^-?\d+$/ && $b =~ /^-?\d+$/) ? $a <=> $b : $a cmp $b } keys %$conv) {
        my $v = $$conv{$k};
        if ($k eq 'BITMASK') {
            ref $v eq 'HASH' or die "$where: BITMASK is not a hash\n";
            $bits = '&[' . join(', ', map { sprintf('(%d, %s)', $_, rust_str($$v{$_})) }
                                     sort { $a <=> $b } keys %$v) . ']';
            next;
        }
        die "$where: unsupported PrintConv key '$k'\n" if ref $v or $k !~ /^-?\d+( -?\d+)*$/;
        push @map, sprintf('(%s, %s)', rust_str($k), rust_str($v));
    }
    return sprintf('Print::Map(&[%s], %s)', join(', ', @map),
                   defined $bits ? "Some($bits)" : 'None');
}

my @out;
for my $id (sort { $a <=> $b } grep { /^\d+$/ } keys %$table) {
    my $entry = $$table{$id};
    my @variants = ref $entry eq 'ARRAY' ? @$entry : ($entry);
    my @rows;
    for my $v (@variants) {
        my $where = sprintf('0x%04x %s', $id, $$v{Name} // '?');
        ref $v eq 'HASH' or die "$where: variant is not a hash\n";
        for my $k (keys %$v) {
            die "$where: unsupported key $k\n"
                unless $k =~ /^(Name|Condition|Notes|Count|Description|PrintConv|PrintConvInv|ValueConv|ValueConvInv)$/;
        }
        my $vconv = 'None';
        if (defined $$v{ValueConv}) {
            ref $$v{ValueConv} eq 'ARRAY' or die "$where: ValueConv is not a list\n";
            $vconv = 'Some(&[' . join(', ', map { defined $_ ? 'Some(' . rust_str($_) . ')' : 'None' }
                                           @{$$v{ValueConv}}) . '])';
        }
        my $pconv;
        if (ref $$v{PrintConv} eq 'ARRAY') {
            $pconv = 'Conv::List(&[' . join(', ', map { print_to_rust($_, $where) } @{$$v{PrintConv}}) . '])';
        } else {
            $pconv = 'Conv::One(' . print_to_rust($$v{PrintConv}, $where) . ')';
        }
        push @rows, sprintf("        Variant {\n            name: %s,\n            cond: %s,\n            value: %s,\n            print: %s,\n        },\n",
            rust_str($$v{Name}), cond_to_rust($$v{Condition}, $where), $vconv, $pconv);
    }
    push @out, sprintf("    (\n        0x%04x,\n        &[\n%s        ],\n    ),\n", $id,
        join('', map { s/^/    /gmr } @rows));
}

print <<"EOT";
//! Auto-generated `%Image::ExifTool::CanonCustom::Functions2`, from ExifTool $version.
//!
//! Generated by scripts/gen_canon_custom2.pl -- DO NOT EDIT MANUALLY.

use std::sync::LazyLock;

use regex_lite::Regex;

use super::canon_custom2::{Conv, Cond, Print, Variant};

EOT
for my $i (0 .. $#regexes) {
    printf "static RE_%d: LazyLock<Regex> = LazyLock::new(|| Regex::new(%s).unwrap());\n",
        $i, rust_str($regexes[$i]);
}
print "\n/// Every custom function, by tag id, with its variants in ExifTool's order.\n";
print "pub(crate) static FUNCTIONS2: &[(u32, &[Variant])] = &[\n";
print @out;
print "];\n";
