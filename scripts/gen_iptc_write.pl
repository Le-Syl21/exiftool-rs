#!/usr/bin/perl
# Generate the IPTC-IIM write table: every tag of the IPTC record tables
# (IPTC.pm), with what the writer needs to encode a value the way
# WriteIPTC.pl does: the record and dataset numbers, the `Format`
# (`string[0,32]`, `digits[8]`, `int16u`, ...), the `List` flag, whether the
# tag is writable, the inverse conversion it takes (IptcDate, IptcTime, the
# CodedCharacterSet escape, or one we have not ported), and the inverse of a
# PrintConv hash.
#
# Usage: perl scripts/gen_iptc_write.pl ../exiftool > src/tags/iptc_write_generated.rs

use strict;
use warnings;

my $dir = shift or die "usage: $0 <path-to-exiftool-checkout>\n";
unshift @INC, "$dir/lib";
require Image::ExifTool;
require Image::ExifTool::IPTC;

sub q_rs {
    my $s = shift;
    $s =~ s/\\/\\\\/g;
    $s =~ s/"/\\"/g;
    $s =~ s/([\x00-\x1f])/sprintf('\\x%02x', ord $1)/ge;
    return "\"$s\"";
}

my $main = Image::ExifTool::GetTagTable('Image::ExifTool::IPTC::Main');
my @rows;
foreach my $rec (sort { $a <=> $b } grep /^\d+$/, keys %$main) {
    my $info = $$main{$rec};
    next unless ref $info eq 'HASH' and $$info{SubDirectory};
    my $table = Image::ExifTool::GetTagTable($$info{SubDirectory}{TagTable});
    foreach my $id (sort { $a <=> $b } grep /^\d+$/, keys %$table) {
        my @infos = Image::ExifTool::GetTagInfoList($table, $id);
        foreach my $ti (@infos) {
            my $format = $$ti{Format} || $$table{FORMAT} || '';
            my $writable = defined $$ti{Writable} ? $$ti{Writable} : $$table{WRITABLE};
            $writable = ($writable and $format) ? 1 : 0;
            my $list = ($$ti{List} or ($$ti{Flags} and (ref $$ti{Flags} ? grep(/^List$/, @{$$ti{Flags}}) : $$ti{Flags} eq 'List'))) ? 1 : 0;
            my $conv = 'None';
            my $vci = $$ti{ValueConvInv};
            my $pci = $$ti{PrintConvInv};
            if (defined $vci and not ref $vci and $vci =~ /IptcDate/) {
                $conv = 'Date';
            } elsif (defined $vci and not ref $vci and $vci =~ /IptcTime/) {
                $conv = 'Time';
            } elsif ($$ti{Name} eq 'CodedCharacterSet') {
                $conv = 'Charset';
            } elsif ((defined $vci and $vci ne '$val') or defined $pci or
                     ($$ti{PrintConv} and ref $$ti{PrintConv} ne 'HASH') or
                     ($$ti{ValueConv} and not defined $vci))
            {
                $conv = 'Unported';
            }
            my @pairs;
            if (ref $$ti{PrintConv} eq 'HASH') {
                my $pc = $$ti{PrintConv};
                foreach my $k (sort keys %$pc) {
                    next if $k =~ /^(OTHER|BITMASK|Notes|PrintHex|PrintString|PrintSort)$/;
                    next if ref $$pc{$k};
                    push @pairs, '(' . q_rs($$pc{$k}) . ', ' . q_rs($k) . ')';
                }
                # a PrintConv hash with an OTHER hook is code we have not ported
                $conv = 'Unported' if $$pc{OTHER} and $conv eq 'None';
            }
            push @rows, sprintf("    IptcWriteInfo { record: %d, dataset: %d, name: %s, format: %s, list: %s, writable: %s, conv: IptcConv::%s, print_inv: &[%s] },\n",
                $rec, $id, q_rs($$ti{Name}), q_rs($format), $list ? 'true' : 'false',
                $writable ? 'true' : 'false', $conv, join(', ', @pairs));
        }
    }
}

print <<'EOT';
//! Auto-generated IPTC-IIM write table, from ExifTool's IPTC.pm.
//!
//! Generated by `scripts/gen_iptc_write.pl`. DO NOT EDIT MANUALLY.

/// The inverse value conversion a tag takes before it is formatted.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IptcConv {
    None,
    /// `IptcDate`: `YYYY:mm:dd` → `YYYYmmdd`.
    Date,
    /// `IptcTime`: `HH:MM:SS[+-HH:MM]` → `HHMMSS+HHMM`.
    Time,
    /// `CodedCharacterSet`: `UTF8` → `ESC % G`.
    Charset,
    /// A conversion written in Perl that has not been ported.
    Unported,
}

/// One IPTC tag as WriteIPTC.pl sees it.
#[derive(Debug)]
pub struct IptcWriteInfo {
    pub record: u8,
    pub dataset: u8,
    pub name: &'static str,
    /// ExifTool `Format`: `string[min,max]`, `digits[n]`, `int16u`, `undef`...
    pub format: &'static str,
    pub list: bool,
    pub writable: bool,
    pub conv: IptcConv,
    /// PrintConv hash, inverted: (printed value, raw value).
    pub print_inv: &'static [(&'static str, &'static str)],
}

/// Every IPTC tag, sorted by record and dataset.
pub static IPTC_WRITE_TAGS: &[IptcWriteInfo] = &[
EOT
print @rows;
print "];\n";
