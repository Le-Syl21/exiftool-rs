#!/bin/sh
# Dump every ExifTool module's data into data/ (see dump_module.pl).
#   sh scripts/dump_all.sh EXIFTOOL_LIB
set -e
lib=$(cd "${1:?usage: dump_all.sh EXIFTOOL_LIB}" && pwd)
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../data"
mkdir -p "$out"
: >"$out/dump.log"
perl "$here/dump_module.pl" "$lib" Image::ExifTool "$out/ExifTool.pld"
echo "Image::ExifTool	ExifTool" >"$out/modules.txt"
perl "$here/dump_module.pl" "$lib" File::RandomAccess "$out/File_RandomAccess.pld"
echo "File::RandomAccess	File_RandomAccess" >>"$out/modules.txt"
(cd "$lib/Image/ExifTool" && find . -name '*.pm' -o -name '*.pl') | sed 's|^\./||; s|\.p[lm]$||' | sort -u | while read -r f; do
    mod="Image::ExifTool::$(echo "$f" | sed 's|/|::|g')"
    name=$(echo "$f" | sed 's|/|_|g')
    if perl "$here/dump_module.pl" "$lib" "$mod" "$out/$name.pld" 2>>"$out/dump.log"; then
        printf '%s\t%s\n' "$mod" "$name" >>"$out/modules.txt"
    else
        echo "FAILED $mod" >>"$out/dump.log"
    fi
done
# The index the runtime embeds (module name, then its dump: a file name
# cannot give the name back, as in Lang/zh_cn).
{
    echo "// Generated by scripts/dump_all.sh: the module dumps, by module name."
    echo "pub static MODULES: &[(&str, &[u8])] = &["
    while IFS='	' read -r m b; do
        echo "    (\"$m\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/data/$b.pld\"))),"
    done <"$out/modules.txt"
    echo "];"
} >"$out/index.rs"
rm "$out/modules.txt"
