#!/usr/bin/perl
# Make the languages ExifTool does not have (Arabic, Bengali, Hindi,
# Portuguese) into Image::ExifTool::Lang modules, from the root crate's
# locale files, and dump them as the other modules are dumped.
#
#   perl scripts/gen_extra_langs.pl EXIFTOOL_LIB [SCRATCH_DIR]
#
# For each language: ../locales/LANG.yml (`TagName: "Description"`) and, if
# there is one, ../locales/values/LANG.tsv (`TagName<TAB>value<TAB>translation`)
# become lib/Image/ExifTool/Lang/LANG.pm in SCRATCH_DIR (default
# target/scratch/extra_langs), in the format of ExifTool's own Lang modules
# (%Image::ExifTool::Lang::LANG::Translate, a description or a hash with
# Description and PrintConv), and dump_module.pl dumps it to
# data/Lang_LANG.pld. Writes data/extra_langs.rs, the index of these dumps
# for the runtime (which keeps them apart from data/index.rs, written by
# dump_all.sh), and data/gui_text.tsv, the `_ui.*` strings of every locale
# for the GUI.
use strict;
use warnings;

my ($lib, $scratch) = @ARGV;
die "usage: $0 EXIFTOOL_LIB [SCRATCH_DIR]\n" unless defined $lib;
my $here = $0;
$here =~ s{/[^/]*$}{} or $here = '.';
my $root = "$here/..";
my $locales = "$root/locales";
$scratch = "$root/target/scratch/extra_langs" unless defined $scratch;

# code, then the name, as ExifTool's %langName gives them
my @extra = (
    [ ar => 'Arabic (العربية)' ],
    [ bn => 'Bengali (বাংলা)' ],
    [ hi => 'Hindi (हिन्दी)' ],
    [ pt => 'Portuguese (Português)' ],
);

# A locale file as the root crate reads it (src/i18n.rs parse_yaml_simple):
# `key: "value"` lines, quotes trimmed, comments and blank lines skipped.
sub read_yaml {
    my $file = shift;
    my %map;
    open my $fh, '<', $file or die "$file: $!\n";
    while (my $line = <$fh>) {
        $line =~ s/^\s+|\s+$//g;
        next if $line eq '' or $line =~ /^#/;
        my ($key, $val) = split /: /, $line, 2;
        next unless defined $val;
        s/^\s+|\s+$//g, s/^"+|"+$//g foreach $key, $val;
        $map{$key} = $val if length $key and length $val;
    }
    close $fh;
    return \%map;
}

sub read_values {
    my $file = shift;
    my %map;
    return \%map unless -e $file;
    open my $fh, '<', $file or die "$file: $!\n";
    while (my $line = <$fh>) {
        chomp $line;
        my ($tag, $eng, $tr) = split /\t/, $line, 3;
        next unless defined $tr and length $tag and length $eng and length $tr;
        $map{$tag}{$eng} = $tr;
    }
    close $fh;
    return \%map;
}

sub quote {
    my $s = shift;
    $s =~ s/([\\'])/\\$1/g;
    return "'$s'";
}

my $langDir = "$scratch/lib/Image/ExifTool/Lang";
system('mkdir', '-p', $langDir) == 0 or die "mkdir $langDir\n";
foreach my $e (@extra) {
    my ($lang, $name) = @$e;
    my $desc = read_yaml("$locales/$lang.yml");
    my $values = read_values("$locales/values/$lang.tsv");
    my %tags = map { $_ => 1 } grep(!/^_ui\./, keys %$desc), keys %$values;
    my $pm = "$langDir/$lang.pm";
    open my $out, '>', $pm or die "$pm: $!\n";
    print $out <<"EOF";
#------------------------------------------------------------------------------
# File:         $lang.pm
#
# Description:  $name language translations, for exiftool-rs
#
# Notes:        Generated by scripts/gen_extra_langs.pl from locales/$lang.yml
#------------------------------------------------------------------------------

package Image::ExifTool::Lang::$lang;

use strict;
use vars qw(\$VERSION);

\$VERSION = '1.00';

%Image::ExifTool::Lang::${lang}::Translate = (
EOF
    foreach my $tag (sort keys %tags) {
        my $d = $$desc{$tag};
        my $pc = $$values{$tag};
        if (not $pc) {
            print $out "   ", quote($tag), " => ", quote($d), ",\n";
            next;
        }
        print $out "   ", quote($tag), " => {\n";
        print $out "      Description => ", quote($d), ",\n" if defined $d;
        print $out "      PrintConv => {\n";
        print $out "        ", quote($_), " => ", quote($$pc{$_}), ",\n" foreach sort keys %$pc;
        print $out "      },\n    },\n";
    }
    print $out ");\n\n1;  #end\n";
    close $out;
    system('perl', '-I', $lib, "$here/dump_module.pl", "$scratch/lib", "Image::ExifTool::Lang::$lang", "$root/data/Lang_$lang.pld") == 0
        or die "dumping $lang failed\n";
}

# the index of the dumps, with the names of the languages
open my $idx, '>', "$root/data/extra_langs.rs" or die "extra_langs.rs: $!\n";
print $idx "// Generated by scripts/gen_extra_langs.pl: the languages exiftool-rs adds to\n";
print $idx "// ExifTool's, and their Lang module dumps.\n";
print $idx "pub static EXTRA_LANGS: &[(&str, &str)] = &[\n";
print $idx "    (\"$$_[0]\", \"$$_[1]\"),\n" foreach @extra;
print $idx "];\n";
print $idx "pub static EXTRA_MODULES: &[(&str, &[u8])] = &[\n";
print $idx "    (\"Image::ExifTool::Lang::$$_[0]\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/data/Lang_$$_[0].pld\"))),\n" foreach @extra;
print $idx "];\n";
close $idx;

# the GUI's strings: language, key (without `_ui.`), text
opendir my $dh, $locales or die "$locales: $!\n";
my @ymls = sort grep /\.yml$/, readdir $dh;
closedir $dh;
open my $ui, '>', "$root/data/gui_text.tsv" or die "gui_text.tsv: $!\n";
foreach my $yml (@ymls) {
    (my $lang = $yml) =~ s/\.yml$//;
    my $map = read_yaml("$locales/$yml");
    foreach my $key (sort grep /^_ui\./, keys %$map) {
        (my $k = $key) =~ s/^_ui\.//;
        print $ui "$lang\t$k\t$$map{$key}\n";
    }
}
close $ui;
