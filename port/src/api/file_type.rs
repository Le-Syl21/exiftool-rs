impl std::fmt::Display for FileType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.description())
    }
}

impl std::fmt::Display for Support {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Support::Read => write!(f, "R"),
            Support::ReadWrite => write!(f, "R/W"),
            Support::ReadWriteCreate => write!(f, "R/W/C"),
        }
    }
}

/// The type ExifTool finds for `header`, the start of a file, from its
/// magic number (ExtractInfo with `FastScan => 3`).
pub fn detect_from_magic(header: &[u8]) -> Option<FileType> {
    let (code, ext) = super::engine::type_of_data(header)?;
    from_exiftool(&code, ext.as_deref())
}

/// The file type for ExifTool's `FileType` and `FileTypeExtension` values.
/// A `FileType` that names a variant of a type (`Extended WEBP`, `ELF
/// executable`) is found by its extension.
pub(crate) fn from_exiftool(code: &str, ext: Option<&str>) -> Option<FileType> {
    from_code(code).or_else(|| {
        let ext = ext?;
        from_code(&ext.to_ascii_uppercase()).or_else(|| ALL_FILE_TYPES.iter().copied().find(|ft| ft.extensions().iter().any(|e| e.eq_ignore_ascii_case(ext))))
    })
}

/// The type of a file with the extension `ext`, if ExifTool knows the
/// extension (`GetFileType`): the type named as the extension when there is
/// one (`cr2` is CR2, processed as TIFF), else the type ExifTool processes
/// it as (`jpg` is JPEG).
pub fn detect_from_extension(ext: &str) -> Option<FileType> {
    let ext = ext.trim_start_matches('.');
    let processed = super::engine::type_of_extension(ext)?;
    from_code(&ext.to_ascii_uppercase())
        .or_else(|| from_code(&processed))
        .or_else(|| ALL_FILE_TYPES.iter().copied().find(|ft| ft.extensions().iter().any(|e| e.eq_ignore_ascii_case(ext))))
}

/// The file type whose code is ExifTool's `FileType` value `code`.
pub fn from_code(code: &str) -> Option<FileType> {
    ALL_FILE_TYPES.iter().copied().find(|ft| ft.code() == code)
}
