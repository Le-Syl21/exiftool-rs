#!/bin/sh
# Dump every ExifTool module's data into data/ (see dump_module.pl).
#   sh scripts/dump_all.sh EXIFTOOL_LIB
set -e
lib=$(cd "${1:?usage: dump_all.sh EXIFTOOL_LIB}" && pwd)
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../data"
mkdir -p "$out"
: >"$out/dump.log"
perl "$here/dump_module.pl" "$lib" Image::ExifTool "$out/ExifTool.pld"
(cd "$lib/Image/ExifTool" && find . -name '*.pm' -o -name '*.pl') | sed 's|^\./||; s|\.p[lm]$||' | sort -u | while read -r f; do
    case "$f" in BuildTagLookup|TagInfoXML|HtmlDump|Plot|Lang/*|Charset/*) continue ;; esac
    mod="Image::ExifTool::$(echo "$f" | sed 's|/|::|g')"
    name=$(echo "$f" | sed 's|/|_|g')
    perl "$here/dump_module.pl" "$lib" "$mod" "$out/$name.pld" 2>>"$out/dump.log" || echo "FAILED $mod" >>"$out/dump.log"
done
# The index the runtime embeds.
{
    echo "// Generated by scripts/dump_all.sh: the module dumps, by module name."
    echo "pub static MODULES: &[(&str, &[u8])] = &["
    for f in "$out"/*.pld; do
        b=$(basename "$f" .pld)
        if [ "$b" = ExifTool ]; then m="Image::ExifTool"; else m="Image::ExifTool::$b"; fi
        echo "    (\"$m\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/data/$b.pld\"))),"
    done
    echo "];"
} >"$out/index.rs"
