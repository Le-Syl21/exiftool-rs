#!/usr/bin/env python3
"""The prototypes of ExifTool's subs, for the interpreter to apply to calls in
Perl code it parses (tables, configs, scripts) when the module was loaded from
its data dump rather than its source.
    gen_prototypes.py EXIFTOOL_LIB > src/runtime/prototypes.rs"""
import os, re, sys

lib = sys.argv[1]
protos = {}
for root, _, files in os.walk(lib):
    for f in files:
        if not f.endswith(('.pm', '.pl')):
            continue
        pkg = 'main'
        key = os.path.relpath(os.path.join(root, f), lib).rsplit('.', 1)[0].replace('/', '::')
        for line in open(os.path.join(root, f), encoding='latin-1'):
            m = re.match(r'package\s+([\w:]+)\s*;', line)
            if m:
                pkg = m.group(1)
            m = re.match(r'sub\s+([\w:]+)\s*\(([^)]*)\)', line)
            if m:
                name = m.group(1) if '::' in m.group(1) else f'{pkg}::{m.group(1)}'
                # a sub declared both in its package's own module and in a
                # file it loads later is known from the module
                if name not in protos or key == pkg:
                    protos[name] = (m.group(2).replace(' ', ''), key)
print('//! AUTO-GENERATED by scripts/gen_prototypes.py from ExifTool\'s lib: the')
print('//! prototype of each sub and the file that declares it (as a module name),')
print('//! by full name, sorted for binary search.')
print()
print('pub static PROTOTYPES: &[(&str, &str, &str)] = &[')
for k in sorted(protos):
    print(f'    ("{k}", "{protos[k][0]}", "{protos[k][1]}"),')
print('];')
