#!/usr/bin/env python3
"""Where each of ExifTool's subs is written: the file (as its %INC key) and
the line of its `sub NAME` (by full name, sorted for binary search). A
ported sub (a native) runs with this location, for die/warn messages as
perl's ("at .../GPS.pm line N.").
    gen_sub_index.py EXIFTOOL_LIB > src/runtime/sub_index.rs"""
import os, re, sys

lib = sys.argv[1]
subs = {}
for root, _, files in os.walk(lib):
    for f in files:
        if not f.endswith(('.pm', '.pl')):
            continue
        path = os.path.join(root, f)
        rel = os.path.relpath(path, lib)
        pkg = 'main'
        for n, line in enumerate(open(path, encoding='latin-1'), 1):
            m = re.match(r'package\s+([\w:]+)\s*;', line)
            if m:
                pkg = m.group(1)
            m = re.match(r'sub\s+([\w:]+)\s*(\([^)]*\))?\s*(\{|$)', line)
            if m and not line.rstrip().endswith(';'):
                name = m.group(1) if '::' in m.group(1) else f'{pkg}::{m.group(1)}'
                subs.setdefault(name, (rel, n))
print("//! AUTO-GENERATED by scripts/gen_sub_index.py from ExifTool's lib: the")
print("//! file (%INC key) and line where each sub is written, by full name, sorted.")
print()
print('pub static SUB_INDEX: &[(&str, &str, u32)] = &[')
for k in sorted(subs):
    print(f'    ("{k}", "{subs[k][0]}", {subs[k][1]}),')
print('];')
